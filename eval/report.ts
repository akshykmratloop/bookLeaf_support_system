import type { TriageDecision } from '../apps/api/src/ai/triage/service.js';
import { costLine, macroF1, priorityTable } from './metrics.js';

export interface EvalCase {
  id: string;
  group: string;
  author: string;
  book: string | null;
  subject: string;
  description: string;
  category: string;
  alsoAccept?: string[];
  priority: string[];
}

export interface CaseResult {
  case: EvalCase;
  ai: TriageDecision | null;
  rules: TriageDecision;
  latencyMs: number;
  error: string | null;
  categoryOk: boolean;
  priorityOk: boolean;
  rulesCategoryOk: boolean;
  rulesPriorityOk: boolean;
  inputTokens?: number;
  outputTokens?: number;
  cacheReadTokens?: number;
  cacheWriteTokens?: number;
}

const pct = (n: number, d: number) =>
  d === 0 ? 'n/a' : `${Math.round((n / d) * 100)}% (${n}/${d})`;
const count = (rs: CaseResult[], f: (r: CaseResult) => boolean) => rs.filter(f).length;

function percentile(values: number[], p: number): number {
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.min(sorted.length - 1, Math.floor((p / 100) * sorted.length))] ?? 0;
}

function byGroup(rs: CaseResult[]): string {
  const groups = [...new Set(rs.map((r) => r.case.group))];
  return groups
    .map((g) => {
      const gr = rs.filter((r) => r.case.group === g);
      return `| ${g} | ${gr.length} | ${pct(
        count(gr, (r) => r.categoryOk),
        gr.length,
      )} | ${pct(
        count(gr, (r) => r.priorityOk),
        gr.length,
      )} |`;
    })
    .join('\n');
}

function confusion(rs: CaseResult[]): string {
  const labels = [
    ...new Set(rs.flatMap((r) => [r.case.category, r.ai?.category ?? 'ERROR'])),
  ].sort();
  const head = `| expected \\ predicted | ${labels.join(' | ')} |\n| --- | ${labels.map(() => '---').join(' | ')} |`;
  const rows = labels
    .filter((l) => rs.some((r) => r.case.category === l))
    .map(
      (exp) =>
        `| ${exp} | ${labels.map((pred) => count(rs, (r) => r.case.category === exp && (r.ai?.category ?? 'ERROR') === pred) || '').join(' | ')} |`,
    );
  return [head, ...rows].join('\n');
}

function misses(rs: CaseResult[]): string {
  const bad = rs.filter((r) => !r.categoryOk || !r.priorityOk);
  if (bad.length === 0) return 'None.';
  return bad
    .map(
      (r) =>
        `- \`${r.case.id}\`: expected ${r.case.category} / ${r.case.priority.join(' or ')}; got ${r.ai ? `${r.ai.category} / ${r.ai.priority}` : r.error}`,
    )
    .join('\n');
}

function confidenceBuckets(rs: CaseResult[]): string {
  const ok = rs.filter((r) => r.ai);
  const high = ok.filter((r) => (r.ai?.confidence ?? 0) >= 0.9);
  const lower = ok.filter((r) => (r.ai?.confidence ?? 0) < 0.9);
  return `| Self-reported confidence | Cases | Category accuracy |\n| --- | --- | --- |\n| high | ${high.length} | ${pct(
    count(high, (r) => r.categoryOk),
    high.length,
  )} |\n| medium / low | ${lower.length} | ${pct(
    count(lower, (r) => r.categoryOk),
    lower.length,
  )} |`;
}

export function renderReport(rs: CaseResult[], model: string, date: string): string {
  const latencies = rs.filter((r) => r.ai).map((r) => r.latencyMs);
  return `# Triage evaluation results

Generated by \`pnpm eval\` on ${date} with model \`${model}\`. Dataset: \`eval/dataset.jsonl\` (${rs.length} hand-labelled cases:
the brief's 7 samples, seed-data scenarios, ambiguous, priority-ordering, prompt-injection, wrong-amount, Hinglish, Hindi
(Devanagari) and adversarial cases).
Priority labels list every acceptable level. **This is a small set written by the developer; treat the numbers as a
sanity check, not a benchmark.** The cases were written by the same developer who wrote the prompts and keyword
rules, and one prompt change (giving triage the royalty status) was made after seeing the \`seed-below-threshold\`
scenario, so this is not an independent held-out test. A separate, independently reviewed set is planned (TASKS Q.5).

## Summary

| | AI triage | Keyword fallback (no AI) |
| --- | --- | --- |
| Category accuracy | ${pct(
    count(rs, (r) => r.categoryOk),
    rs.length,
  )} | ${pct(
    count(rs, (r) => r.rulesCategoryOk),
    rs.length,
  )} |
| Priority within accepted levels | ${pct(
    count(rs, (r) => r.priorityOk),
    rs.length,
  )} | ${pct(
    count(rs, (r) => r.rulesPriorityOk),
    rs.length,
  )} |
| Category macro-F1 | ${macroF1(rs, (r) => r.ai?.category ?? undefined).toFixed(3)} | ${macroF1(rs, (r) => r.rules.category ?? undefined).toFixed(3)} |
| Errors (no result) | ${count(rs, (r) => r.error !== null)} | 0 |

Latency of AI calls: p50 ${percentile(latencies, 50)} ms · p95 ${percentile(latencies, 95)} ms (single run, sequential, local machine).

${costLine(rs.filter((r) => r.ai))}

## Priority: too low or too high

${priorityTable(rs)}

## By group (AI)

| Group | Cases | Category | Priority |
| --- | --- | --- | --- |
${byGroup(rs)}

## Category confusion matrix (AI)

${confusion(rs)}

## Confidence buckets (AI)

${confidenceBuckets(rs)}

## Misses (AI)

${misses(rs)}
`;
}

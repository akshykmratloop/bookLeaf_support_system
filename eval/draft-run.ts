/**
 * Reply-draft evaluation: writes a live AI draft for a sample of the triage cases, runs the
 * server-side checker on each, and writes docs/qa/draft-eval.md. Usage (from apps/api):
 * `npx tsx --env-file=<.env> ../../eval/draft-run.ts [model]`. One model call per case.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { TicketCategory } from '@bookleaf/shared';
import { sampleCustomer } from '../apps/api/test/fixtures/host.js';
import { factsFor } from '../apps/api/src/host/facts.js';
import { royaltySignals } from '../apps/api/src/ai/domain/signals.js';
import { anthropicProvider } from '../apps/api/src/ai/providers/anthropic/provider.js';
import {
  DEFAULT_AI_SETTINGS,
  estimateCostMicros,
  findModel,
} from '../apps/api/src/ai/providers/catalog.js';
import { runAiDraft } from '../apps/api/src/ai/drafting/service.js';
import type { DraftInput } from '../apps/api/src/ai/drafting/types.js';
import type { EvalCase } from './report.js';

/** A spread of the triage set: every brief and seed case, plus multilingual and hostile ones. */
const SAMPLE =
  /^(brief|seed|inject-01|wrong-amount|hinglish-0[1-4]|hindi-0[1-3]|adversarial-0[1-3])/;

const root = (p: string) => fileURLToPath(new URL(p, import.meta.url));

interface DraftRow {
  id: string;
  passed: boolean;
  figureIssues: string[];
  placeholders: number;
  latencyMs: number;
  costMicros: number;
  error: string | null;
  echoesClaim: boolean;
}

function toInput(c: EvalCase): DraftInput {
  const customer = sampleCustomer(c.author);
  const facts = factsFor(customer, c.book);
  const book = customer.items.find((i) => i.id === c.book) ?? null;
  return {
    category: c.category as TicketCategory,
    authorName: customer.name,
    book: book ? { externalId: book.id, title: book.title } : null,
    facts,
    royalty: royaltySignals(facts, c.book),
    subject: c.subject,
    authorMessages: [c.description],
    lastTeamReply: null,
    ignorePhrases: customer.items.map((i) => i.title),
  };
}

const FIGURE = /^(UNSUPPORTED|CLAIM)/;
/** Amounts the author asserted that no record supports: a good reply must not repeat them. */
const AUTHOR_CLAIMS: Record<string, string> = {
  'wrong-amount': '50,000',
  'adversarial-02': '1,00,000',
};

async function draftOne(c: EvalCase, model: string): Promise<DraftRow> {
  const provider = anthropicProvider({ apiKey: process.env.ANTHROPIC_API_KEY ?? '' });
  const base = { id: c.id, latencyMs: 0, costMicros: 0, placeholders: 0, echoesClaim: false };
  try {
    const { draft, run } = await runAiDraft(provider, model, toInput(c));
    const claim = AUTHOR_CLAIMS[c.id];
    return {
      ...base,
      passed: draft.check.passed,
      figureIssues: draft.check.issues.map((i) => i.code).filter((code) => FIGURE.test(code)),
      placeholders: (draft.body.match(/\[CONFIRM:/g) ?? []).length,
      latencyMs: run.latencyMs,
      costMicros: estimateCostMicros(findModel('anthropic', model), run.usage) ?? 0,
      error: null,
      echoesClaim: claim ? draft.body.includes(claim) : false,
    };
  } catch (err) {
    const error = err instanceof Error ? err.name : 'Error';
    return { ...base, passed: false, figureIssues: [], error };
  }
}

const pctl = (xs: number[], p: number) =>
  [...xs].sort((a, b) => a - b)[Math.min(xs.length - 1, Math.floor((p / 100) * xs.length))] ?? 0;

function render(rows: DraftRow[], model: string): string {
  const ok = rows.filter((r) => !r.error);
  const lat = ok.map((r) => r.latencyMs);
  const usd = rows.reduce((a, r) => a + r.costMicros, 0) / 1_000_000;
  const line = (r: DraftRow) =>
    `| ${r.id} | ${r.error ?? (r.passed ? 'pass' : 'blocked')} | ${r.figureIssues.join(', ') || '—'} | ${r.placeholders} | ${r.echoesClaim ? 'YES' : 'no'} | ${r.latencyMs} |`;
  return `# Reply-draft evaluation

Generated by \`eval/draft-run.ts\` on ${new Date().toISOString().slice(0, 10)} with model \`${model}\`, ${rows.length} cases
sampled from \`eval/dataset.jsonl\`. Each draft is checked by the same server-side checker that gates every reply.
"Blocked" means a human must fix or override before sending; it is the safety net working, not a sent error.

| Measure | Result |
| --- | --- |
| Drafts that pass the checker first time | ${ok.filter((r) => r.passed).length}/${rows.length} |
| Drafts with an unsupported figure or claim | ${ok.filter((r) => r.figureIssues.length).length}/${rows.length} |
| Unsupported figures/claims in total | ${ok.reduce((a, r) => a + r.figureIssues.length, 0)} |
| Drafts that repeat an amount the author made up | ${ok.filter((r) => r.echoesClaim).length}/${Object.keys(AUTHOR_CLAIMS).filter((k) => rows.some((r) => r.id === k)).length} |
| Drafts asking the agent to confirm something ([CONFIRM: …]) | ${ok.filter((r) => r.placeholders).length}/${rows.length} |
| Errors (no draft; the template would be used) | ${rows.length - ok.length} |
| Latency p50 / p95 | ${pctl(lat, 50)} ms / ${pctl(lat, 95)} ms |
| Estimated cost | $${usd.toFixed(4)} in total (≈ $${((usd / rows.length) * 1000).toFixed(2)} per 1,000 drafts) |

| Case | Checker | Issues | Placeholders | Repeats author's amount | Latency ms |
| --- | --- | --- | --- | --- | --- |
${rows.map(line).join('\n')}
`;
}

async function main(): Promise<void> {
  if (!process.env.ANTHROPIC_API_KEY) throw new Error('ANTHROPIC_API_KEY is not set.');
  const model = process.argv[2] ?? DEFAULT_AI_SETTINGS.draftModel;
  const cases = readFileSync(root('./dataset.jsonl'), 'utf8')
    .split('\n')
    .filter((l) => l.trim())
    .map((l) => JSON.parse(l) as EvalCase)
    .filter((c) => SAMPLE.test(c.id));
  const rows: DraftRow[] = [];
  for (const c of cases) {
    rows.push(await draftOne(c, model));
    process.stdout.write(
      `${c.id}: ${rows.at(-1)?.error ?? (rows.at(-1)?.passed ? 'pass' : 'blocked')}\n`,
    );
  }
  writeFileSync(root('../docs/qa/draft-eval.md'), render(rows, model));
}

main().catch((err: unknown) => {
  process.stderr.write(`Draft eval failed: ${err instanceof Error ? err.message : String(err)}\n`);
  process.exit(1);
});
